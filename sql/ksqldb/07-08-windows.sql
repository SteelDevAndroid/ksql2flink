CREATE OR REPLACE TABLE VA_PEAGE_CLASSIFICATIONINFOQUALITE WITH (CLEANUP_POLICY='compact,delete', KAFKA_TOPIC='va.peage.classificationInfoQualite', KEY_FORMAT='json', PARTITIONS=6, REPLICAS=4, RETENTION_MS=604800000, VALUE_FORMAT='json') AS SELECT
  VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->STATION KEYSTATION,
  VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->LANE KEYLANE,
  VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.STATIONLANE KEYSTATIONLANE,
  AS_VALUE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->STATION) STATION,
  AS_VALUE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->LANE) LANE,
  AS_VALUE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.STATIONLANE) STATIONLANE,
  AS_VALUE(LATEST_BY_OFFSET(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CREATIONDATE)) CREATIONDATE,
  AS_VALUE(SUM((CASE WHEN (REDUCE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CLASS, false, (S, X) => (S OR (X->CLASSORIGIN = 'Manual'))) OR REDUCE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CLASS, false, (S, X) => (S OR (X->CLASSORIGIN = 'FC')))) THEN 1 ELSE 0 END))) NBCLASSIFWRONGORIGIN,
  AS_VALUE((SUM((CASE WHEN (REDUCE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CLASS, false, (S, X) => (S OR (X->CLASSORIGIN = 'Manual'))) OR REDUCE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CLASS, false, (S, X) => (S OR (X->CLASSORIGIN = 'FC')))) THEN 1 ELSE 0 END)) / CAST(COUNT(*) AS DOUBLE))) RATIO,
  COUNT(*) NBPASSAGE,
  1 COUNTKEY,
  WINDOWSTART WINDOW_START,
  WINDOWEND WINDOW_END
FROM VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND
WINDOW SESSION ( 60 MINUTES )
WHERE (((REDUCE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CLASS, false, (S, X) => (S OR (X->CLASSTYPE = 'TarifiedClass'))) = true) AND (REDUCE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CLASS, false, (S, X) => (S OR (X->CLASSTYPE = 'PostDTO'))) = false)) AND (VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CALLERMODE <> 'TD'))
GROUP BY VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.STATIONLANE, VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->STATION, VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->LANE
HAVING (((SUM((CASE WHEN (REDUCE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CLASS, false, (S, X) => (S OR (X->CLASSORIGIN = 'Manual'))) OR REDUCE(VA_PEAGE_CLASSIFICATION_FLOWS_EXTEND.FLOW->CLASS, false, (S, X) => (S OR (X->CLASSORIGIN = 'FC')))) THEN 1 ELSE 0 END)) / CAST(COUNT(*) AS DOUBLE)) > 0.3) AND (COUNT(*) >= 20))
EMIT CHANGES;

