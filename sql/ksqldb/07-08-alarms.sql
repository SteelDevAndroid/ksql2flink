CREATE OR REPLACE STREAM VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM (STATION STRING, LANE STRING, STATIONLANE STRING, CREATIONDATE STRING, NBCLASSIFWRONGORIGIN INTEGER, COUNTKEY INTEGER, WINDOW_START TIMESTAMP, WINDOW_END TIMESTAMP) WITH (CLEANUP_POLICY='delete', KAFKA_TOPIC='va.peage.classificationInfoQualite', KEY_FORMAT='KAFKA', PARTITIONS=6, REPLICAS=4, VALUE_FORMAT='JSON');

CREATE OR REPLACE STREAM VA_PEAGE_CLASSIFICATIONINFOQUALITE_COUNT_STREAM (NBTOTALVOIE INTEGER, COUNTKEY INTEGER, COUNTKEYVALUE INTEGER, WINDOW_START TIMESTAMP, WINDOW_END TIMESTAMP) WITH (CLEANUP_POLICY='delete', KAFKA_TOPIC='va.peage.classificationInfoQualite.Count', KEY_FORMAT='KAFKA', VALUE_FORMAT='JSON');

CREATE OR REPLACE TABLE VA_PEAGE_CLASSIFICATION_ALARMEUNITAIRE WITH (CLEANUP_POLICY='compact', KAFKA_TOPIC='va.peage.classificationAlarme', KEY_FORMAT='json', PARTITIONS=6, REPLICAS=4, RETENTION_MS=604800000, VALUE_FORMAT='json') AS SELECT
  3 IDSOURCEALARME,
  3 IDTYPEALARME,
  LATEST_BY_OFFSET(VA_PEAGE_CLASSIFICATIONINFOQUALITE_COUNT_STREAM.NBTOTALVOIE) PRIORITE,
  0 IDCLASSE,
  1 IDCRITICITE,
  '' IDENSEMBLEEQUIPEMENT,
  '01' IDEQUIPEMENT,
  VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.STATION GARE,
  AS_VALUE(VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.STATION) IDGARE,
  0 IDTYPEINCIDENT,
  '' LIBELLEDETAILINCIDENT,
  'Voie' LIBELLEENSEMBLEEQUIPEMENT,
  'Classification' LIBELLEEQUIPEMENT,
  'Classif: origine de la classe anormale (Voie)' LIBELLEINCIDENT,
  VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.LANE VOIE,
  AS_VALUE(VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.LANE) LIBELLEVOIE,
  '' IDTYPEVOIE,
  0 NUMEROTRANSACTION,
  0 TYPEVOIEENTREESORTIE,
  SUBSTRING(AS_VALUE(VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.STATION), 4, 2) CODESOCIETE,
  SUBSTRING(AS_VALUE(VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.STATION), 1, 5) SOCIETE,
  LATEST_BY_OFFSET(VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.NBCLASSIFWRONGORIGIN) TOTAL,
  LATEST_BY_OFFSET(FORMAT_TIMESTAMP(PARSE_TIMESTAMP(VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.CREATIONDATE, 'yyyy-MM-dd''T''HH:mm:ss.SSSSSSSX', 'UTC'), 'yyyy-MM-dd''T''HH:mm:ss''Z''', 'Europe/Paris')) HORODATEALARME
FROM VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM
INNER JOIN VA_PEAGE_CLASSIFICATIONINFOQUALITE_COUNT_STREAM VA_PEAGE_CLASSIFICATIONINFOQUALITE_COUNT_STREAM WITHIN 1 MINUTES ON ((VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.COUNTKEY = VA_PEAGE_CLASSIFICATIONINFOQUALITE_COUNT_STREAM.COUNTKEYVALUE))
GROUP BY VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.STATION, VA_PEAGE_CLASSIFICATIONINFOQUALITE_STREAM.LANE
HAVING (LATEST_BY_OFFSET(VA_PEAGE_CLASSIFICATIONINFOQUALITE_COUNT_STREAM.NBTOTALVOIE) < 30)
EMIT CHANGES;

