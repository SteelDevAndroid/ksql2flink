CREATE STREAM STREAM_VA_PEAGE_BACKOFFICE_SOCLEET_REFCOMPTEUR (ID INTEGER, R_COMPTEUR_TYPEID INTEGER, R_FREQUENCEID INTEGER, R_OPERATIONID INTEGER, R_MODE_REGLEMENTID INTEGER, R_TRANSACTION_ETATID INTEGER) WITH (CLEANUP_POLICY='delete', KAFKA_TOPIC='va.peage.backoffice.socleET.ref_compteur', KEY_FORMAT='KAFKA', VALUE_FORMAT='JSON');

CREATE STREAM STREAM_VA_PEAGE_BACKOFFICE_SOCLEET_REFINDICATEUR (ID INTEGER, R_INDICATEUR_TYPEID INTEGER, R_FREQUENCEID INTEGER) WITH (CLEANUP_POLICY='delete', KAFKA_TOPIC='va.peage.backoffice.socleET.ref_indicateur', KEY_FORMAT='KAFKA', VALUE_FORMAT='JSON');

CREATE STREAM VA_PEAGE_BACKOFFICE_SOCLEET_ETANCHEITE (R_COMPTEURID INTEGER, R_MODE_REGLEMENTID INTEGER, R_OPERATIONID INTEGER, R_VOIEID INTEGER, R_GAREID INTEGER, R_SOCIETEID INTEGER, R_PARTENAIREID INTEGER, R_TRANSACTION_ETATID INTEGER, R_TRANSACTION_MODIFICATION_TYPEID INTEGER, IDT_TRAN_PEA STRING, MONTANT_TRANSACTION DOUBLE, DATE_OPERATION DOUBLE, DATE_COMPTABLE DOUBLE) WITH (CLEANUP_POLICY='delete', KAFKA_TOPIC='va.peage.backoffice.socleET.etancheite', KEY_FORMAT='KAFKA', VALUE_FORMAT='JSON');

CREATE TABLE TABLE_VA_PEAGE_BACKOFFICE_SOCLEET_REF_COMPTEURS WITH (CLEANUP_POLICY='compact', KAFKA_TOPIC='TABLE_VA_PEAGE_BACKOFFICE_SOCLEET_REF_COMPTEURS', PARTITIONS=6, REPLICAS=4, RETENTION_MS=604800000) AS SELECT
  P.ID ID,
  COUNT(*) COUNT,
  LATEST_BY_OFFSET(P.R_COMPTEUR_TYPEID) R_COMPTEUR_TYPEID,
  LATEST_BY_OFFSET(P.R_FREQUENCEID) R_FREQUENCEID,
  LATEST_BY_OFFSET(P.R_OPERATIONID) R_OPERATIONID,
  LATEST_BY_OFFSET(P.R_MODE_REGLEMENTID) R_MODE_REGLEMENTID,
  LATEST_BY_OFFSET(P.R_TRANSACTION_ETATID) R_TRANSACTION_ETATID
FROM STREAM_VA_PEAGE_BACKOFFICE_SOCLEET_REFCOMPTEUR P
WHERE (((((P.R_COMPTEUR_TYPEID IS NOT NULL) AND (P.R_FREQUENCEID IS NOT NULL)) AND (P.R_OPERATIONID IS NOT NULL)) AND (P.R_MODE_REGLEMENTID IS NOT NULL)) AND (P.R_TRANSACTION_ETATID IS NOT NULL))
GROUP BY P.ID
EMIT CHANGES;

CREATE TABLE TABLE_VA_PEAGE_BACKOFFICE_SOCLEET_REF_INDICATEURS WITH (CLEANUP_POLICY='compact', KAFKA_TOPIC='TABLE_VA_PEAGE_BACKOFFICE_SOCLEET_REF_INDICATEURS', PARTITIONS=6, REPLICAS=4, RETENTION_MS=604800000) AS SELECT
  P.ID ID,
  COUNT(*) COUNT,
  LATEST_BY_OFFSET(P.R_INDICATEUR_TYPEID) R_INDICATEUR_TYPEID,
  LATEST_BY_OFFSET(P.R_FREQUENCEID) R_FREQUENCEID
FROM STREAM_VA_PEAGE_BACKOFFICE_SOCLEET_REFINDICATEUR P
WHERE ((P.R_INDICATEUR_TYPEID IS NOT NULL) AND (P.R_FREQUENCEID IS NOT NULL))
GROUP BY P.ID
EMIT CHANGES;

CREATE STREAM VA_PEAGE_BACKOFFICE_SOCLEET_FILTER_REF_COMPTEUR WITH (CLEANUP_POLICY='delete', KAFKA_TOPIC='VA_PEAGE_BACKOFFICE_SOCLEET_FILTER_REF_COMPTEUR', PARTITIONS=6, REPLICAS=4, RETENTION_MS=604800000) AS SELECT
  T.R_COMPTEURID R_COMPTEURID,
  T.R_VOIEID R_VOIEID,
  T.R_GAREID R_GAREID,
  T.R_SOCIETEID R_SOCIETEID,
  T.R_PARTENAIREID R_PARTENAIREID,
  T.IDT_TRAN_PEA IDT_TRAN_PEA,
  (CASE WHEN (ABS(C.R_COMPTEUR_TYPEID) = ABS(1)) THEN CAST(1 AS DOUBLE) ELSE T.MONTANT_TRANSACTION END) VALEUR,
  T.MONTANT_TRANSACTION MONTANT_TRANSACTION,
  T.DATE_OPERATION DATE_OPERATION,
  T.DATE_COMPTABLE DATE_COMPTABLE,
  C.R_FREQUENCEID R_FREQUENCEID,
  C.R_MODE_REGLEMENTID C_R_MODE_REGLEMENTID,
  C.R_COMPTEUR_TYPEID R_COMPTEUR_TYPEID
FROM VA_PEAGE_BACKOFFICE_SOCLEET_ETANCHEITE T
INNER JOIN TABLE_VA_PEAGE_BACKOFFICE_SOCLEET_REF_COMPTEURS C ON ((T.R_COMPTEURID = C.ID))
WHERE (CASE WHEN (ABS(C.R_MODE_REGLEMENTID) = ABS(1)) THEN ((T.R_OPERATIONID = C.R_OPERATIONID) AND (T.R_TRANSACTION_ETATID = C.R_TRANSACTION_ETATID)) ELSE (((T.R_OPERATIONID = C.R_OPERATIONID) AND (T.R_TRANSACTION_ETATID = C.R_TRANSACTION_ETATID)) AND (T.R_MODE_REGLEMENTID = C.R_MODE_REGLEMENTID)) END)
EMIT CHANGES;

CREATE STREAM VA_PEAGE_BACKOFFICE_SOCLEET_FILTER_REF_INDICATEUR WITH (CLEANUP_POLICY='delete', KAFKA_TOPIC='VA_PEAGE_BACKOFFICE_SOCLEET_FILTER_REF_INDICATEUR', PARTITIONS=6, REPLICAS=4, RETENTION_MS=604800000) AS SELECT
  T.R_COMPTEURID R_COMPTEURID,
  T.R_VOIEID R_VOIEID,
  T.R_GAREID R_GAREID,
  T.R_SOCIETEID R_SOCIETEID,
  T.R_PARTENAIREID R_PARTENAIREID,
  T.IDT_TRAN_PEA IDT_TRAN_PEA,
  (CASE WHEN (ABS(C.R_INDICATEUR_TYPEID) = ABS(1)) THEN CAST(1 AS DOUBLE) ELSE T.MONTANT_TRANSACTION END) VALEUR,
  T.DATE_OPERATION DATE_OPERATION,
  C.R_FREQUENCEID R_FREQUENCEID,
  C.R_INDICATEUR_TYPEID R_INDICATEUR_TYPEID,
  T.DATE_COMPTABLE DATE_COMPTABLE
FROM VA_PEAGE_BACKOFFICE_SOCLEET_ETANCHEITE T
INNER JOIN TABLE_VA_PEAGE_BACKOFFICE_SOCLEET_REF_INDICATEURS C ON ((T.R_COMPTEURID = C.ID))
EMIT CHANGES;
